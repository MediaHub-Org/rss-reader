let locale: UiLocale = 'en';

export function resolveLocale(preference: LanguagePreference, navigatorLanguage?: string): UiLocale {
  if (preference === 'en' || preference === 'es') return preference;
  const language = (navigatorLanguage ?? (typeof navigator !== 'undefined' ? navigator.language : 'en')).toLowerCase();
  return language.startsWith('es') ? 'es' : 'en';
}

export function setLocale(next: UiLocale): void {
  locale = next;
  if (typeof document !== 'undefined') document.documentElement.lang = next;
}

export function getLocale(): UiLocale {
  return locale;
}

export function t(source: string, vars?: Vars): string {
  const template = locale === 'es' ? (es[source] ?? source) : source;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

/** Pick a singular/plural source string and interpolate the count. */
export function plural(count: number, one: string, many: string): string {
  return t(count === 1 ? one : many, { count });
}
